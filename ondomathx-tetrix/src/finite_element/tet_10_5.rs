/// Gradient interpolation: computes  output = M · input  (10→15).
///
/// output[k] = Σ_i GRADIENT_MAT[k][i] · input[i]
/// where k = j*3+d  (j ∈ 0..5 quadrature points, d ∈ {0,1,2}).
pub fn gradient_interpolation_by_array(input: &[f64], output: &mut [f64]) {
    let input = &input[..10];
    for k in 0..15 {
        let row = &GRADIENT_MAT[k];
        let mut acc = 0.0_f64;
        for j in 0..10 {
            acc += row[j] * input[j];
        }
        output[k] = acc;
    }
}

/// Transpose gradient interpolation: computes  output = M^T · input  (15→10).
///
/// output[i] += Σ_k GRADIENT_MAT[k][i] · input[k]
pub fn transpose_gradient_interpolation_by_array(input: &[f64], output: &mut [f64]) {
    let input = &input[..15];
    for x in output[..10].iter_mut() {
        *x = 0.0;
    }
    for k in 0..15 {
        let row = &GRADIENT_MAT[k];
        let x = input[k];
        for i in 0..10 {
            output[i] += row[i] * x;
        }
    }
}
