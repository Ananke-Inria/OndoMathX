pub fn transpose_gradient_interpolation(input: &[f64], output: &mut [f64]) {
    // axpy-style: for each input slot k, accumulate GRADIENT_MAT[k] (a row of 15
    // contiguous values) scaled by input[k] into output.  Both GRADIENT_MAT and
    // input are accessed sequentially, and the inner loop of 15 vectorizes just
    // like the forward pass.
    let input = &input[..42];
    for x in output[..15].iter_mut() {
        *x = 0.0;
    }
    for k in 0..42 {
        let row = &GRADIENT_MAT[k];
        let x = input[k];
        for i in 0..15 {
            output[i] += row[i] * x;
        }
    }
}

pub fn gradient_interpolation(input: &[f64], output: &mut [f64]) {
    // Slicing to a fixed length lets the compiler elide bounds checks and
    // auto-vectorize the inner loop (it now knows the range is exactly 15).
    let input = &input[..15];
    for k in 0..42 {
        let row = &GRADIENT_MAT[k];
        let mut acc = 0.0_f64;
        for j in 0..15 {
            acc += row[j] * input[j];
        }
        output[k] = acc;
    }
}
